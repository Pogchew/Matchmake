-- Seed the owner timeline with real recent records so the first dashboard load
-- has useful history. Future writes are captured by the triggers above.
insert into public.admin_activity_logs (
  actor_user_id,
  entity_type,
  entity_id,
  action,
  target_label,
  status,
  details,
  metadata,
  created_at
)
select
  auth_actor.id,
  event.entity_type,
  event.entity_id,
  event.action,
  event.target_label,
  event.status,
  event.details,
  jsonb_build_object('backfilled', true),
  event.created_at
from (
  select
    app_user.id as actor_user_id,
    'users'::text as entity_type,
    app_user.id as entity_id,
    'created user'::text as action,
    app_user.display_name as target_label,
    'success'::text as status,
    app_user.account_type as details,
    app_user.created_at
  from public.users app_user

  union all

  select
    organization.org_admin_id,
    'organizations',
    organization.id,
    'created organization',
    organization.name,
    case when organization.verified_flag then 'success' else 'pending' end,
    coalesce(organization.region, organization.type),
    organization.created_at
  from public.organizations organization

  union all

  select
    organization.org_admin_id,
    'teams',
    team.id,
    'created team',
    team.name,
    'success',
    team.game_title,
    team.created_at
  from public.teams team
  join public.organizations organization on organization.id = team.org_id

  union all

  select
    organization.org_admin_id,
    'scrim_requests',
    scrim.id,
    'created scrim',
    scrim.game_title || ' scrim',
    case when scrim.status in ('pending', 'matched', 'accepted') then 'pending' else 'success' end,
    'Status: ' || scrim.status,
    scrim.created_at
  from public.scrim_requests scrim
  join public.teams team on team.id = scrim.posting_team_id
  join public.organizations organization on organization.id = team.org_id

  union all

  select
    message.sender_user_id,
    'scrim_messages',
    message.id,
    'sent message',
    coalesce(message.sender_display_name, 'Participant') || ' in scrim chat',
    'success',
    'Conversation activity',
    message.created_at
  from public.scrim_messages message

  union all

  select
    review.created_by,
    'team_match_reviews',
    review.id,
    'submitted review',
    review.game_title || ' review',
    case when review.manual_edit_required then 'pending' else 'success' end,
    case when review.manual_edit_required then 'Manual review required' else coalesce(review.match_result, review.parser_status) end,
    review.created_at
  from public.team_match_reviews review
) event
left join auth.users auth_actor on auth_actor.id = event.actor_user_id
where not exists (
  select 1
  from public.admin_activity_logs existing
  where existing.entity_type = event.entity_type
    and existing.entity_id = event.entity_id
    and existing.action = event.action
    and existing.created_at = event.created_at
)
order by event.created_at desc
limit 250;
