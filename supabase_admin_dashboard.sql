-- Matchmake owner-only administration and live activity logging.
-- Apply after the core schema and scoped RLS policy files.

create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create table if not exists private.owner_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  label text not null default 'Owner',
  created_at timestamptz not null default now()
);

alter table private.owner_accounts enable row level security;
revoke all on table private.owner_accounts from public, anon, authenticated;

create or replace function private.is_matchmake_owner()
returns boolean
language sql
stable
security definer
set search_path = private, auth, pg_temp
as $$
  select exists (
    select 1
    from private.owner_accounts owner_account
    where owner_account.user_id = (select auth.uid())
  )
$$;

revoke all on function private.is_matchmake_owner() from public;
grant execute on function private.is_matchmake_owner() to authenticated;

create or replace function public.is_matchmake_owner()
returns boolean
language sql
stable
security invoker
set search_path = private, public, pg_temp
as $$
  select private.is_matchmake_owner()
$$;

revoke all on function public.is_matchmake_owner() from public, anon;
grant execute on function public.is_matchmake_owner() to authenticated;

create table if not exists public.admin_activity_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  entity_type text not null,
  entity_id uuid,
  action text not null,
  target_label text not null,
  status text not null default 'success'
    check (status in ('success', 'pending', 'failed', 'open')),
  details text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_activity_logs_created_at_idx
  on public.admin_activity_logs(created_at desc);
create index if not exists admin_activity_logs_entity_idx
  on public.admin_activity_logs(entity_type, entity_id, created_at desc);
create index if not exists admin_activity_logs_actor_idx
  on public.admin_activity_logs(actor_user_id, created_at desc);

alter table public.admin_activity_logs enable row level security;
revoke all on table public.admin_activity_logs from public, anon, authenticated;
grant select, insert on table public.admin_activity_logs to authenticated;
grant usage on sequence public.admin_activity_logs_id_seq to authenticated;

drop policy if exists "Matchmake owners can read activity logs" on public.admin_activity_logs;
create policy "Matchmake owners can read activity logs"
  on public.admin_activity_logs
  for select
  to authenticated
  using ((select private.is_matchmake_owner()));

drop policy if exists "Authenticated users can insert launch analytics events" on public.admin_activity_logs;
create policy "Authenticated users can insert launch analytics events"
  on public.admin_activity_logs
  for insert
  to authenticated
  with check (
    actor_user_id = (select auth.uid())
    and entity_type = 'analytics'
    and action in ('signup_completed', 'scrim_posted', 'extraction_completed', 'extraction_failed')
    and status in ('success', 'pending', 'failed', 'open')
    and jsonb_typeof(metadata) = 'object'
  );

create or replace function private.capture_matchmake_activity()
returns trigger
language plpgsql
security definer
set search_path = public, private, auth, pg_temp
as $$
declare
  row_data jsonb;
  old_data jsonb;
  activity_actor uuid;
  activity_action text;
  activity_target text;
  activity_status text := 'success';
  activity_details text;
begin
  row_data := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  old_data := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;
  activity_actor := (select auth.uid());
  activity_action := lower(tg_op);

  if tg_table_name = 'users' then
    activity_target := coalesce(row_data ->> 'display_name', row_data ->> 'email', 'User');
    activity_action := case tg_op when 'INSERT' then 'created user' when 'UPDATE' then 'updated user' else 'removed user' end;
    activity_details := coalesce(row_data ->> 'account_type', 'Account');
  elsif tg_table_name = 'organizations' then
    activity_target := coalesce(row_data ->> 'name', 'Organization');
    activity_action := case tg_op when 'INSERT' then 'created organization' when 'UPDATE' then 'updated organization' else 'removed organization' end;
    if tg_op = 'UPDATE' and (old_data ->> 'verified_flag') is distinct from (row_data ->> 'verified_flag') then
      activity_details := case when (row_data ->> 'verified_flag')::boolean then 'Organization verified' else 'Verification removed' end;
    else
      activity_details := coalesce(row_data ->> 'region', row_data ->> 'type', 'Organization record');
    end if;
  elsif tg_table_name = 'teams' then
    activity_target := coalesce(row_data ->> 'name', 'Team');
    activity_action := case tg_op when 'INSERT' then 'created team' when 'UPDATE' then 'updated roster' else 'removed team' end;
    activity_details := coalesce(row_data ->> 'game_title', 'Team record');
  elsif tg_table_name = 'scrim_requests' then
    activity_target := coalesce(row_data ->> 'game_title', 'Scrim') || ' scrim';
    activity_action := case tg_op when 'INSERT' then 'created scrim' when 'UPDATE' then 'updated scrim' else 'removed scrim' end;
    if tg_op = 'UPDATE' and (old_data ->> 'status') is distinct from (row_data ->> 'status') then
      activity_details := coalesce(old_data ->> 'status', 'unknown') || ' to ' || coalesce(row_data ->> 'status', 'unknown');
    else
      activity_details := 'Status: ' || coalesce(row_data ->> 'status', 'unknown');
    end if;
    activity_status := case
      when row_data ->> 'status' in ('pending', 'matched', 'accepted') then 'pending'
      when row_data ->> 'status' in ('declined', 'cancelled', 'expired') then 'open'
      else 'success'
    end;
  elsif tg_table_name = 'scrim_messages' then
    activity_target := coalesce(row_data ->> 'sender_display_name', 'Participant') || ' in scrim chat';
    activity_action := case tg_op when 'INSERT' then 'sent message' when 'UPDATE' then 'updated message' else 'removed message' end;
    activity_details := 'Conversation activity';
  elsif tg_table_name = 'team_match_reviews' then
    activity_actor := coalesce(activity_actor, nullif(row_data ->> 'created_by', '')::uuid);
    activity_target := coalesce(row_data ->> 'game_title', 'Match') || ' review';
    activity_action := case tg_op when 'INSERT' then 'submitted review' when 'UPDATE' then 'updated review' else 'removed review' end;
    activity_details := case
      when coalesce((row_data ->> 'manual_edit_required')::boolean, false) then 'Manual review required'
      else coalesce(row_data ->> 'match_result', row_data ->> 'parser_status', 'Review saved')
    end;
    activity_status := case
      when coalesce((row_data ->> 'manual_edit_required')::boolean, false) then 'pending'
      else 'success'
    end;
  else
    return coalesce(new, old);
  end if;

  insert into public.admin_activity_logs (
    actor_user_id,
    entity_type,
    entity_id,
    action,
    target_label,
    status,
    details,
    metadata
  ) values (
    activity_actor,
    tg_table_name,
    nullif(row_data ->> 'id', '')::uuid,
    activity_action,
    activity_target,
    activity_status,
    activity_details,
    jsonb_build_object('operation', tg_op)
  );

  return coalesce(new, old);
end
$$;

revoke all on function private.capture_matchmake_activity() from public, anon, authenticated;

create or replace function public.track_matchmake_analytics_event(
  event_name text,
  event_status text default 'success',
  target_label text default 'Launch analytics',
  entity_id uuid default null,
  event_details text default null,
  event_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security invoker
set search_path = public, private, auth, pg_temp
as $$
declare
  normalized_event text := lower(btrim(coalesce(event_name, '')));
  normalized_status text := lower(btrim(coalesce(event_status, 'success')));
  safe_metadata jsonb := '{}'::jsonb;
begin
  if (select auth.uid()) is null then
    return;
  end if;

  if normalized_event not in (
    'signup_completed',
    'scrim_posted',
    'extraction_completed',
    'extraction_failed'
  ) then
    return;
  end if;

  if normalized_status not in ('success', 'pending', 'failed', 'open') then
    normalized_status := 'success';
  end if;

  if event_metadata is not null and jsonb_typeof(event_metadata) = 'object' then
    safe_metadata := event_metadata;
  end if;

  insert into public.admin_activity_logs (
    actor_user_id,
    entity_type,
    entity_id,
    action,
    target_label,
    status,
    details,
    metadata
  ) values (
    (select auth.uid()),
    'analytics',
    entity_id,
    normalized_event,
    left(coalesce(nullif(target_label, ''), 'Launch analytics'), 120),
    normalized_status,
    left(coalesce(event_details, ''), 300),
    safe_metadata || jsonb_build_object('source', 'launch_analytics_rpc')
  );
end
$$;

revoke all on function public.track_matchmake_analytics_event(text, text, text, uuid, text, jsonb) from public, anon;
grant execute on function public.track_matchmake_analytics_event(text, text, text, uuid, text, jsonb) to authenticated;

